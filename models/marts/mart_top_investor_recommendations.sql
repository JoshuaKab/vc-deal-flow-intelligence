    STARTUP_INDUSTRY,
    STARTUP_COUNTRY,
    STARTUP_STAGE,

    RECOMMENDATION_RANK,

    INVESTOR_SLUG,
    INVESTOR_NAME,
    INVESTOR_TYPE,
