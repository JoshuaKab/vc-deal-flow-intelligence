SELECT
    INVESTOR_SLUG,
    INVESTOR_NAME,
    INVESTOR_TYPE,
    INVESTOR_HQ_COUNTRY,

    COUNT(*) AS TOTAL_RECOMMENDATIONS,

    COUNT(DISTINCT COMPANY_ID) AS UNIQUE_STARTUPS_MATCHED,

    COUNT_IF(RECOMMENDATION_RANK = 1) AS FIRST_PLACE_RANKINGS,

    ROUND(AVG(COMPATIBILITY_SCORE), 2) AS AVG_COMPATIBILITY_SCORE,

    ROUND(AVG(RECOMMENDATION_RANK), 2) AS AVG_RECOMMENDATION_RANK,

    ROUND(AVG(EVIDENCE_COVERAGE) * 100, 2) AS AVG_EVIDENCE_COVERAGE_PCT,

    ROUND(MAX(COMPATIBILITY_SCORE), 2) AS BEST_COMPATIBILITY_SCORE

FROM {{ ref('int_startup_investor_compatibility') }}

GROUP BY
    INVESTOR_SLUG,
    INVESTOR_NAME,
    INVESTOR_TYPE,
    INVESTOR_HQ_COUNTRY

ORDER BY
    TOTAL_RECOMMENDATIONS DESC,
    AVG_COMPATIBILITY_SCORE DESC