SELECT
    COMPANY_ID,
    COMPANY_NAME,
    STARTUP_INDUSTRY,
    STARTUP_COUNTRY,
    STARTUP_STAGE,

    COUNT(*) AS TOTAL_RECOMMENDED_INVESTORS,

    COUNT_IF(RECOMMENDATION_RANK = 1) AS TOP_RANKED_INVESTORS,

    ROUND(AVG(COMPATIBILITY_SCORE), 2) AS AVG_COMPATIBILITY_SCORE,

    ROUND(MAX(COMPATIBILITY_SCORE), 2) AS BEST_COMPATIBILITY_SCORE,

    ROUND(AVG(EVIDENCE_COVERAGE) * 100, 2) AS AVG_EVIDENCE_COVERAGE_PCT,

    COUNT_IF(COMPATIBILITY_SCORE >= 80) AS HIGH_COMPATIBILITY_MATCHES,

    MAX(
        CASE
            WHEN RECOMMENDATION_RANK = 1
            THEN INVESTOR_NAME
        END
    ) AS TOP_RECOMMENDED_INVESTOR

FROM {{ ref('int_startup_investor_compatibility') }}

GROUP BY
    COMPANY_ID,
    COMPANY_NAME,
    STARTUP_INDUSTRY,
    STARTUP_COUNTRY,
    STARTUP_STAGE

ORDER BY
    BEST_COMPATIBILITY_SCORE DESC