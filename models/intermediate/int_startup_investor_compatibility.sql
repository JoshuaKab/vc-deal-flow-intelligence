SELECT
    -- Matching information
    m.STARTUP_IDX,
    m.COMPANY_ID,
    m.COMPANY_NAME,
    m.INVESTOR_IDX,
    m.INVESTOR_SLUG,
    m.INVESTOR_NAME,
    m.INVESTOR_TYPE,
    m."RANK" AS RECOMMENDATION_RANK,

    -- Compatibility scores
    m.COMPATIBILITY_SCORE,
    m.EVIDENCE_COVERAGE,
    m.SEMANTIC_SCORE,
    m.INDUSTRY_SCORE,
    m.GEOGRAPHY_SCORE,
    m.STAGE_SCORE,
    m.TECHNOLOGY_SCORE,
    m.ACTIVITY_SCORE,
    m.BUSINESS_MODEL_SCORE,
    m.COMPATIBILITY_BAND,
    m.EVIDENCE_BAND,

    -- Startup information
    s.ONE_LINER AS STARTUP_ONE_LINER,
    s.LONG_DESCRIPTION AS STARTUP_LONG_DESCRIPTION,
    s.WEBSITE AS STARTUP_WEBSITE,
    s.COUNTRY AS STARTUP_COUNTRY,
    s.CITY AS STARTUP_CITY,
    s.INDUSTRY AS STARTUP_INDUSTRY,
    s.SUBINDUSTRY AS STARTUP_SUBINDUSTRY,
    s.STAGE AS STARTUP_STAGE,
    s.STATUS AS STARTUP_STATUS,
    s.YEAR_FOUNDED,
    s.TEAM_SIZE,
    s.FOUNDERS_COUNT,
    s.COUNTRY_NORMALIZED AS STARTUP_COUNTRY_NORMALIZED,

    -- Investor information
    i.INVESTOR_DOMAIN,
    i.HQ_COUNTRY AS INVESTOR_HQ_COUNTRY,
    i.HQ_CITY AS INVESTOR_HQ_CITY,
    i.DEALS AS INVESTOR_DEALS,
    i.LEAD_DEALS AS INVESTOR_LEAD_DEALS,
    i.PORTFOLIO_COMPANIES AS INVESTOR_PORTFOLIO_COMPANIES,
    i.FIRST_DEAL_YEAR,
    i.LAST_DEAL_YEAR,
    i.DEALS_2025_2026,
    i.TOP_SECTORS AS INVESTOR_TOP_SECTORS,
    i.TOP_COUNTRIES AS INVESTOR_TOP_COUNTRIES,
    i.SEED_SHARE,
    i.EARLY_SHARE,
    i.GROWTH_SHARE,
    i.MEDIAN_ROUND_USD,
    i.FLIAR_PROFILE_URL,
    i.INVESTOR_SECTOR_LIST,
    i.MAPPED_STARTUP_INDUSTRIES,
    i.MAPPING_STATUS

FROM {{ ref('stg_investor_matches') }} m

LEFT JOIN {{ ref('stg_startup_profiles') }} s
    ON m.COMPANY_ID = s.COMPANY_ID

LEFT JOIN {{ ref('stg_investor_profiles') }} i
    ON m.INVESTOR_SLUG = i.INVESTOR_SLUG